package com.yandex.mapkit;

public class ScreenPoint {
    private float x;
    private float y;

    public ScreenPoint() {}

    public ScreenPoint(float x, float y) {
        this.x = x;
        this.y = y;
    }

    public float getX() { return this.x; }
    public float getY() { return this.y; }
}
